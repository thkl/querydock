interface ConstraintRow {
  name: string;
  constraintType: 'p' | 'u' | 'f' | 'c' | 'x';
  fieldNames: string[];
  definition: string;
  referencedSchema: string | null;
  referencedTable: string | null;
  referencedFieldNames: string[];
}

export interface VerifiedPostgresConnection {
  serverVersion: string;
}

export class PostgresConnectionError extends Error {
  constructor(
    message: string,
    readonly safeMessage: string,
  ) {
    super(message);
    this.name = 'PostgresConnectionError';
  }
}

export class MigrationPlanError extends Error {
  constructor(
    readonly kind: 'not-found' | 'drift' | 'review-mismatch' | 'invalid' | 'unknown',
    message: string,
  ) {
    super(message);
    this.name = 'MigrationPlanError';
  }
}

export class PostgresAdapter {
  private readonly logger = new Logger(PostgresAdapter.name);

  schemaCapabilities(): SchemaCapabilities {
    return { createTableIfNotExists: true };
  }

  editableFieldTypes() {
    return [...POSTGRES_EDITABLE_FIELD_TYPES];
  }

  async verifyConnection(configuration: PostgresConnectRequest): Promise<VerifiedPostgresConnection> {
    return this.withClient(configuration, async (client) => {
      const result = await client.query<{ serverVersion: string }>(
        'SELECT current_setting(\'server_version\') AS "serverVersion"',
      );
      return { serverVersion: result.rows[0]?.serverVersion ?? 'unknown' };
    });
  }

  async listResources(configuration: PostgresConnectRequest): Promise<ResourceDescriptor[]> {
    return this.withClient(configuration, async (client) => {
      const result = await client.query<ResourceRow>(`
        SELECT
          namespace.nspname AS schema,
          relation.relname AS name,
          CASE relation.relkind
            WHEN 'r' THEN 'table'
            WHEN 'p' THEN 'partitionedTable'
            WHEN 'v' THEN 'view'
            WHEN 'm' THEN 'materializedView'
            WHEN 'f' THEN 'foreignTable'
          END AS kind,
          COALESCE(information_table.is_insertable_into = 'YES', false) AS "isUpdatable"
        FROM pg_catalog.pg_class AS relation
        JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
        LEFT JOIN information_schema.tables AS information_table
          ON information_table.table_schema = namespace.nspname
          AND information_table.table_name = relation.relname
        WHERE relation.relkind IN ('r', 'p', 'v', 'm', 'f')
          AND information_table.table_name IS NOT NULL
          AND namespace.nspname <> 'information_schema'
          AND namespace.nspname NOT LIKE 'pg\\_%' ESCAPE '\\'
        ORDER BY namespace.nspname, relation.relname
      `);

      return result.rows;
    });
  }

  async inspectTable(
    configuration: PostgresConnectRequest,
    schema: string,
    table: string,
  ): Promise<TableSnapshot | undefined> {
    validatePostgresIdentifier(schema, 'schema');
    validatePostgresIdentifier(table, 'table');
    return this.withClient(configuration, (client) => this.inspectTableWithClient(client, schema, table));
  }

  async foreignKeyFieldChoices(
    configuration: PostgresConnectRequest,
    sourceSchema: string,
    sourceTable: string,
    targetSchema: string,
    targetTable: string,
    localFieldNames: string[],
  ): Promise<{ fieldSets: { fieldNames: string[]; label: string; compatible: boolean; reason: string | null }[] }> {
    for (const [name, kind] of [[sourceSchema, 'schema'], [targetSchema, 'schema'], [sourceTable, 'table'], [targetTable, 'table']] as const) {
      validatePostgresIdentifier(name, kind);
    }
    if (!localFieldNames.length || localFieldNames.length > 32) {
      throw new MigrationPlanError('invalid', 'Choose between one and 32 local fields for the foreign key.');
    }
    return this.withClient(configuration, async (client) => {
      const target = await inspectForeignKeyTarget(client, targetSchema, targetTable);
      if (!target || (target.kind !== 'table' && target.kind !== 'partitionedTable')) return { fieldSets: [] };
      const [localTypes, targetTypes] = await Promise.all([
        client.query<{ name: string; typeName: string }>(`
          SELECT attribute.attname AS name, pg_catalog.format_type(attribute.atttypid, attribute.atttypmod) AS "typeName"
          FROM pg_catalog.pg_class relation
          JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
          JOIN pg_catalog.pg_attribute attribute ON attribute.attrelid = relation.oid
          WHERE namespace.nspname = $1 AND relation.relname = $2
            AND attribute.attnum > 0 AND NOT attribute.attisdropped AND attribute.attname = ANY($3::text[])
        `, [sourceSchema, sourceTable, localFieldNames]),
        client.query<{ name: string; typeName: string }>(`
          SELECT attribute.attname AS name, pg_catalog.format_type(attribute.atttypid, attribute.atttypmod) AS "typeName"
          FROM pg_catalog.pg_class relation
          JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
          JOIN pg_catalog.pg_attribute attribute ON attribute.attrelid = relation.oid
          WHERE namespace.nspname = $1 AND relation.relname = $2
            AND attribute.attnum > 0 AND NOT attribute.attisdropped
        `, [targetSchema, targetTable]),
      ]);
      const localByName = new Map(localTypes.rows.map((field) => [field.name, field.typeName]));
      const targetByName = new Map(targetTypes.rows.map((field) => [field.name, field.typeName]));
      const fieldSets = target.uniqueFieldSets
        .map((fieldNames) => {
          let reason: string | null = null;
          if (localTypes.rows.length !== localFieldNames.length) {
            reason = 'One or more selected local fields could not be found. Refresh the source table and try again.';
          } else if (fieldNames.length !== localFieldNames.length) {
            reason = `This key contains ${fieldNames.length} field${fieldNames.length === 1 ? '' : 's'}; select the same number of local fields.`;
          } else {
            const incompatibleIndex = fieldNames.findIndex((fieldName, index) =>
              !typesCanReference(localByName.get(localFieldNames[index]) ?? '', targetByName.get(fieldName) ?? ''));
            if (incompatibleIndex >= 0) {
              const localField = localFieldNames[incompatibleIndex];
              const targetField = fieldNames[incompatibleIndex];
              reason = `Local field "${localField}" (${localByName.get(localField) ?? 'unknown type'}) is not compatible with target field "${targetField}" (${targetByName.get(targetField) ?? 'unknown type'}).`;
            }
          }
          return { fieldNames, label: fieldNames.join(', '), compatible: reason === null, reason };
        });
      return { fieldSets };
    });
  }

  async previewMigration(
    configuration: PostgresConnectRequest,
    request: MigrationPreviewRequest,
  ): Promise<MigrationPreviewResponse> {
    validatePostgresIdentifier(request.schema, 'schema');
    validatePostgresIdentifier(request.table, 'table');
    return this.withClient(configuration, async (client) => {
      if (request.baselineFingerprint === null) {
        if (!request.operations.length || request.operations.some((operation) => operation.kind !== 'createTable')) {
          throw new MigrationPlanError('invalid', 'A new-table plan must contain only create-table operations.');
        }
        const operations = request.operations;
        const tableNames = new Set<string>();
        for (const operation of operations) {
          if (operation.kind !== 'createTable') continue;
          validatePostgresIdentifier(operation.table, 'table');
          if (tableNames.has(operation.table)) {
            throw new MigrationPlanError('invalid', `The table "${operation.table}" appears more than once in this runbook.`);
          }
          tableNames.add(operation.table);
          if (operation.ifNotExists && !this.schemaCapabilities().createTableIfNotExists) {
            throw new MigrationPlanError('invalid', 'This database adapter does not support CREATE TABLE IF NOT EXISTS.');
          }
          await assertNewTableTarget(client, request.schema, operation.table, operation.ifNotExists);
        }
        return {
          baselineFingerprint: null,
          statements: operations.map((operation) => {
            if (operation.kind !== 'createTable') throw new MigrationPlanError('invalid', 'Invalid create-table operation.');
            return createTableStatement(request.schema, operation.table, operation.fields, operation.ifNotExists);
          }),
          warnings: createTableWarnings(request.schema, operations),
        };
      }
      if (request.operations.some((operation) => operation.kind === 'createTable')) {
        throw new MigrationPlanError('invalid', 'Create-table operations require a new-table baseline.');
      }
      validateTableLifecycleOperations(request.operations);
      const snapshot = await this.inspectTableWithClient(client, request.schema, request.table);
      if (!snapshot) throw new MigrationPlanError('not-found', 'The requested table was not found or is not visible.');
      if (snapshot.fingerprint !== request.baselineFingerprint) {
        throw new MigrationPlanError('drift', 'The table changed since it was loaded. Refresh the schema before drafting a migration.');
      }
      await validateForeignKeyTargets(client, snapshot, request.operations);
      await validateTableLifecycleTarget(client, snapshot, request.operations);
      const preview = createMigrationPreview(snapshot, request);
      const warnings = collectMigrationWarnings(snapshot, request.operations);
      return { baselineFingerprint: snapshot.fingerprint, statements: preview, warnings };
    });
  }

  async applyMigration(
    configuration: PostgresConnectRequest,
    request: MigrationApplyRequest,
  ): Promise<MigrationApplyResponse> {
    validatePostgresIdentifier(request.schema, 'schema');
    validatePostgresIdentifier(request.table, 'table');
    return this.withClient(configuration, async (client) => {
      await client.query('BEGIN');
      let commitStarted = false;
      try {
        if (request.baselineFingerprint === null) {
          if (!request.operations.length || request.operations.some((operation) => operation.kind !== 'createTable')) {
            throw new MigrationPlanError('invalid', 'A new-table plan must contain only create-table operations.');
          }
          const operations = request.operations;
          const tableNames = new Set<string>();
          for (const operation of operations) {
            if (operation.kind !== 'createTable') continue;
            validatePostgresIdentifier(operation.table, 'table');
            if (tableNames.has(operation.table)) {
              throw new MigrationPlanError('invalid', `The table "${operation.table}" appears more than once in this runbook.`);
            }
            tableNames.add(operation.table);
          }
          for (const table of [...tableNames].sort()) {
            await client.query('SELECT pg_advisory_xact_lock(hashtext($1))', [`querydock:create:${request.schema}.${table}`]);
          }
          for (const operation of operations) {
            if (operation.kind === 'createTable') {
              if (operation.ifNotExists && !this.schemaCapabilities().createTableIfNotExists) {
                throw new MigrationPlanError('invalid', 'This database adapter does not support CREATE TABLE IF NOT EXISTS.');
              }
              await assertNewTableTarget(client, request.schema, operation.table, operation.ifNotExists);
            }
          }
          const statements = operations.map((operation) => {
            if (operation.kind !== 'createTable') throw new MigrationPlanError('invalid', 'Invalid create-table operation.');
            return createTableStatement(request.schema, operation.table, operation.fields, operation.ifNotExists);
          });
          if (!sameStatements(statements, request.reviewedStatements)) {
            throw new MigrationPlanError('review-mismatch', 'The reviewed SQL no longer matches this create-table plan. Generate a new preview before applying.');
          }
          const warnings = createTableWarnings(request.schema, operations);
          if (!sameStatements(warnings, request.acknowledgedWarnings)) {
            throw new MigrationPlanError('review-mismatch', 'Review and acknowledge the current create-table warnings before applying.');
          }
          for (const statement of statements) await client.query(statement);
          const createdSnapshots = await Promise.all(operations.map(async (operation) => {
            if (operation.kind !== 'createTable') throw new MigrationPlanError('invalid', 'Invalid create-table operation.');
            const snapshot = await this.inspectTableWithClient(client, request.schema, operation.table);
            if (!snapshot) throw new MigrationPlanError('unknown', `The table "${operation.table}" was created, but its resulting structure could not be confirmed.`);
            return snapshot;
          }));
          commitStarted = true;
          const commitResult = await client.query('COMMIT');
          if (commitResult.command !== 'COMMIT') {
            throw new MigrationPlanError('unknown', 'The server could not confirm that the table creation committed.');
          }
          return { appliedStatements: statements, snapshots: createdSnapshots };
        }
        validateTableLifecycleOperations(request.operations);
        await client.query(`LOCK TABLE ${quoteIdentifier(request.schema)}.${quoteIdentifier(request.table)} IN ACCESS EXCLUSIVE MODE`);
        const snapshot = await this.inspectTableWithClient(client, request.schema, request.table);
        if (!snapshot) throw new MigrationPlanError('not-found', 'The requested table was not found or is not visible.');
        if (snapshot.fingerprint !== request.baselineFingerprint) {
          throw new MigrationPlanError('drift', 'The table changed since this preview was generated. Refresh the schema and review the draft again.');
        }

        await validateForeignKeyTargets(client, snapshot, request.operations);
        await validateTableLifecycleTarget(client, snapshot, request.operations);
        const statements = createMigrationPreview(snapshot, request);
        if (!sameStatements(statements, request.reviewedStatements)) {
          throw new MigrationPlanError('review-mismatch', 'The reviewed SQL no longer matches this migration plan. Generate a new preview before applying.');
        }
        const warnings = collectMigrationWarnings(snapshot, request.operations);
        if (!sameStatements(warnings, request.acknowledgedWarnings)) {
          throw new MigrationPlanError('review-mismatch', 'Review and acknowledge the current migration warnings before applying.');
        }

        for (const statement of statements) await client.query(statement);
        const lifecycle = request.operations[0];
        const resultSchema = lifecycle?.kind === 'renameTable' ? lifecycle.newName : request.table;
        const updatedSnapshot = lifecycle?.kind === 'dropTable'
          ? null
          : await this.inspectTableWithClient(client, request.schema, resultSchema);
        if (lifecycle?.kind !== 'dropTable' && !updatedSnapshot) {
          throw new MigrationPlanError('unknown', 'The migration ran, but the resulting schema could not be confirmed.');
        }
        commitStarted = true;
        const commitResult = await client.query('COMMIT');
        if (commitResult.command !== 'COMMIT') {
          throw new MigrationPlanError('unknown', 'The server could not confirm that the migration transaction committed.');
        }
        return { appliedStatements: statements, snapshots: updatedSnapshot ? [updatedSnapshot] : [] };
      } catch (error) {
        let rollbackConfirmed = false;
        try {
          await client.query('ROLLBACK');
          rollbackConfirmed = true;
        } catch {
          // A lost database connection can leave the transaction outcome uncertain.
        }
        if (error instanceof MigrationPlanError) throw error;
        if (commitStarted || !rollbackConfirmed) {
          throw new MigrationPlanError('unknown', 'The transaction outcome could not be confirmed. Inspect the database before retrying.');
        }
        throw new MigrationPlanError('invalid', migrationDatabaseMessage(error));
      }
    });
  }

  private async inspectTableWithClient(
    client: Client,
    schema: string,
    table: string,
  ): Promise<TableSnapshot | undefined> {
    const resources = await client.query<InspectedResourceRow>(`
      SELECT
        namespace.nspname AS schema,
        relation.relname AS name,
        CASE relation.relkind
          WHEN 'r' THEN 'table'
          WHEN 'p' THEN 'partitionedTable'
          WHEN 'v' THEN 'view'
          WHEN 'm' THEN 'materializedView'
          WHEN 'f' THEN 'foreignTable'
        END AS kind,
        (relation.relkind IN ('r', 'p')
          AND pg_catalog.pg_has_role(current_user, relation.relowner, 'USAGE')
          AND pg_catalog.has_schema_privilege(current_user, namespace.oid, 'USAGE')) AS "canAlter",
        COALESCE(information_table.is_insertable_into = 'YES', false) AS "isUpdatable"
      FROM pg_catalog.pg_class AS relation
      JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
      LEFT JOIN information_schema.tables AS information_table
        ON information_table.table_schema = namespace.nspname
        AND information_table.table_name = relation.relname
      WHERE namespace.nspname = $1 AND relation.relname = $2
        AND relation.relkind IN ('r', 'p', 'v', 'm', 'f')
        AND information_table.table_name IS NOT NULL
    `, [schema, table]);
    const resource = resources.rows[0];
    if (!resource) return undefined;

    const fieldResult = await client.query<FieldRow>(`
      SELECT
        columns.ordinal_position::int AS "ordinalPosition",
        columns.column_name AS name,
        columns.udt_schema AS "typeSchema",
        columns.udt_name AS "typeName",
        columns.data_type AS "dataType",
        columns.character_maximum_length AS "characterMaximumLength",
        columns.numeric_precision AS "numericPrecision",
        columns.numeric_scale AS "numericScale",
        (columns.is_nullable = 'YES') AS nullable,
        columns.column_default AS "defaultExpression",
        CASE columns.identity_generation
          WHEN 'ALWAYS' THEN 'always'
          WHEN 'BY DEFAULT' THEN 'byDefault'
          ELSE NULL
        END AS "identityGeneration",
        (columns.is_generated = 'ALWAYS') AS generated,
        columns.generation_expression AS "generationExpression"
      FROM information_schema.columns AS columns
      WHERE columns.table_schema = $1 AND columns.table_name = $2
      ORDER BY columns.ordinal_position
    `, [schema, table]);

    const constraintResult = await client.query<ConstraintRow>(`
      SELECT
        constraint_row.conname AS name,
        constraint_row.contype AS "constraintType",
        ARRAY(
          SELECT attribute.attname::text
          FROM unnest(constraint_row.conkey) WITH ORDINALITY AS key_column(attnum, ordinal)
          JOIN pg_catalog.pg_attribute AS attribute
            ON attribute.attrelid = constraint_row.conrelid
            AND attribute.attnum = key_column.attnum
          ORDER BY key_column.ordinal
        ) AS "fieldNames",
        pg_catalog.pg_get_constraintdef(constraint_row.oid, true) AS definition,
        referenced_namespace.nspname AS "referencedSchema",
        referenced_relation.relname AS "referencedTable",
        ARRAY(
          SELECT referenced_attribute.attname::text
          FROM unnest(constraint_row.confkey) WITH ORDINALITY AS key_column(attnum, ordinal)
          JOIN pg_catalog.pg_attribute AS referenced_attribute
            ON referenced_attribute.attrelid = constraint_row.confrelid
            AND referenced_attribute.attnum = key_column.attnum
          ORDER BY key_column.ordinal
        ) AS "referencedFieldNames"
      FROM pg_catalog.pg_constraint AS constraint_row
      JOIN pg_catalog.pg_class AS relation ON relation.oid = constraint_row.conrelid
      JOIN pg_catalog.pg_namespace AS namespace ON namespace.oid = relation.relnamespace
      LEFT JOIN pg_catalog.pg_class AS referenced_relation
        ON referenced_relation.oid = constraint_row.confrelid
      LEFT JOIN pg_catalog.pg_namespace AS referenced_namespace
        ON referenced_namespace.oid = referenced_relation.relnamespace
      WHERE namespace.nspname = $1 AND relation.relname = $2
        AND constraint_row.contype IN ('p', 'u', 'f', 'c', 'x')
      ORDER BY constraint_row.conname
    `, [schema, table]);

    const fields: TableFieldDescriptor[] = fieldResult.rows.map((field) => {
      const editableType = fieldTypeFor(field.dataType);
      return {
        ...field,
        editableType,
        editable: resource.canAlter && editableType !== null && !field.generated && !field.identityGeneration,
        identityEditable: resource.canAlter && identityGenerationSupported(field.dataType) && !field.generated,
      };
    });
    const constraints: TableConstraintDescriptor[] = constraintResult.rows.map((row) => ({
      name: row.name,
      kind: constraintKind(row.constraintType),
      editable: resource.canAlter && ['p', 'u', 'f', 'c'].includes(row.constraintType),
      fieldNames: row.fieldNames ?? [],
      definition: row.definition,
      referencedSchema: row.referencedSchema,
      referencedTable: row.referencedTable,
      referencedFieldNames: row.referencedFieldNames ?? [],
    }));
    const baseline = {
      schema: resource.schema,
      name: resource.name,
      kind: resource.kind,
      fields,
      constraints,
    };
    const fingerprintBaseline = {
      ...baseline,
      constraints: constraints.map((constraint) => ({
        name: constraint.name,
        kind: constraint.kind,
        fieldNames: constraint.fieldNames,
        definition: constraint.definition,
        referencedSchema: constraint.referencedSchema,
        referencedTable: constraint.referencedTable,
        referencedFieldNames: constraint.referencedFieldNames,
      })),
    };
    const fingerprint = createHash('sha256').update(JSON.stringify(fingerprintBaseline)).digest('hex');

    return {
      ...baseline,
      editableFieldTypes: [...POSTGRES_EDITABLE_FIELD_TYPES],
      editableIdentityGenerations: resource.canAlter && ['table', 'partitionedTable'].includes(resource.kind)
        ? [...POSTGRES_EDITABLE_IDENTITY_GENERATIONS]
        : [],
      editableConstraintKinds: resource.canAlter && ['table', 'partitionedTable'].includes(resource.kind)
        ? [...POSTGRES_EDITABLE_CONSTRAINT_KINDS]
        : [],
      fields,
      canAlter: resource.canAlter,
      fingerprint,
    };
  }

  async previewSchemaFieldDraft(
    configuration: PostgresConnectRequest,
    request: SchemaFieldDraftRequest,
  ): Promise<SchemaFieldDraftResponse> {
    validatePostgresIdentifier(request.schema, 'schema');
    validatePostgresIdentifier(request.table, 'table');
    return this.withClient(configuration, async (client) => {
      const snapshot = await this.inspectTableWithClient(client, request.schema, request.table);
      if (!snapshot) throw new MigrationPlanError('not-found', 'The requested table was not found or is not visible.');
      if (snapshot.fingerprint !== request.baselineFingerprint) {
        throw new MigrationPlanError('drift', 'The table changed since it was loaded. Refresh the schema before drafting a migration.');
      }
      const draftOperation = normalizeFieldDraft(snapshot, request.draft);
      const operations = draftOperation ? [...request.operations, draftOperation] : request.operations;
      const plan: MigrationPreviewRequest = {
        schema: request.schema,
        table: request.table,
        baselineFingerprint: request.baselineFingerprint,
        operations,
      };
      const statements = operations.length ? createMigrationPreview(snapshot, plan) : [];
      const warnings = operations.length ? collectMigrationWarnings(snapshot, operations) : [];
      return { baselineFingerprint: snapshot.fingerprint, statements, warnings, operations };
    });
  }

  private async withClient<T>(
    configuration: PostgresConnectRequest,
    action: (client: Client) => Promise<T>,
  ): Promise<T> {
    const client = new Client({
      host: configuration.host,
      port: configuration.port,
      database: configuration.database,
      user: configuration.username,
      password: configuration.password,
      connectionTimeoutMillis: 8000,
      ssl: configuration.sslMode === 'disable'
        ? false
        : { rejectUnauthorized: configuration.sslMode === 'verify-full' },
      application_name: 'QueryDock',
    });

    try {
      await client.connect();
      return await action(client);
    } catch (error) {
      if (error instanceof MigrationPlanError) throw error;
      const databaseError = typeof error === 'object' && error !== null
        ? error as { code?: unknown; message?: unknown }
        : undefined;
      const code = typeof databaseError?.code === 'string' ? databaseError.code : 'unknown';
      const message = typeof databaseError?.message === 'string' ? databaseError.message : 'Unknown PostgreSQL error';
      this.logger.warn(`PostgreSQL request failed (SQLSTATE/code ${code}): ${message}`);
      throw new PostgresConnectionError(
        message,
        safeDatabaseMessage(error),
      );
    } finally {
      await client.end().catch(() => undefined);
    }
  }
}

async function assertNewTableTarget(client: Client, schema: string, table: string, ifNotExists = false): Promise<void> {
  const schemaResult = await client.query<{ exists: boolean; canCreate: boolean }>(
    `SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = $1) AS "exists",
      has_schema_privilege(current_user, $1, 'CREATE') AS "canCreate"`,
    [schema],
  );
  if (!schemaResult.rows[0]?.exists) {
    throw new MigrationPlanError('invalid', `The schema "${schema}" does not exist or is not visible.`);
  }
  if (!schemaResult.rows[0].canCreate) {
    throw new MigrationPlanError('invalid', `The connected PostgreSQL user cannot create tables in schema "${schema}".`);
  }
  const tableResult = await client.query<{ exists: boolean }>(`
    SELECT EXISTS (
      SELECT 1 FROM pg_catalog.pg_class relation
      JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
      WHERE namespace.nspname = $1 AND relation.relname = $2
    ) AS "exists"
  `, [schema, table]);
  if (tableResult.rows[0]?.exists && !ifNotExists) {
    throw new MigrationPlanError('invalid', `An object named "${schema}.${table}" already exists.`);
  }
}

function createTableWarnings(schema: string, operations: SchemaOperation[]): string[] {
  const tableNames = operations.flatMap((operation) =>
    operation.kind === 'createTable' && operation.ifNotExists ? [operation.table] : []);
  if (!tableNames.length) return [];
  return [`CREATE TABLE IF NOT EXISTS leaves existing objects unchanged and does not compare their structure with this draft: ${tableNames.map((table) => `"${schema}.${table}"`).join(', ')}.`];
}

/** @internal Pure SQL generation helper; exported for the migration-plan unit tests. */
export function createTableStatement(schema: string, table: string, fields: CreateTableField[], ifNotExists = false): string {
  validatePostgresIdentifier(schema, 'schema');
  validatePostgresIdentifier(table, 'table');
  if (!fields.length) throw new MigrationPlanError('invalid', 'Add at least one field to the table.');
  const seenNames = new Set<string>();
  const definitions = fields.map((field) => {
    const name = field.name.trim();
    validateFieldName(name);
    if (seenNames.has(name)) throw new MigrationPlanError('invalid', `The field "${name}" appears more than once.`);
    seenNames.add(name);
    const descriptor = POSTGRES_EDITABLE_FIELD_TYPES.find(({ value }) => value === field.type);
    if (!descriptor) throw new MigrationPlanError('invalid', `Choose a field type supported by PostgreSQL for "${name}".`);
    if (field.identityGeneration && !descriptor.identityGenerationSupported) {
      throw new MigrationPlanError('invalid', `Identity generation is not supported for the ${descriptor.label} field "${name}".`);
    }
    if (field.identityGeneration && field.defaultExpression?.trim()) {
      throw new MigrationPlanError('invalid', `The identity field "${name}" cannot also have a default expression.`);
    }
    if (field.identityGeneration && field.nullable) {
      throw new MigrationPlanError('invalid', `The identity field "${name}" must be non-nullable.`);
    }
    const typeDetails = (field.typeDetails ?? '').trim();
    let characterMaximumLength: number | null = null;
    let numericPrecision: number | null = null;
    let numericScale: number | null = null;
    if (typeDetails && field.type === 'varchar') {
      if (!/^\d+$/.test(typeDetails)) throw new MigrationPlanError('invalid', `For Varchar field "${name}", enter a positive maximum length, such as 255.`);
      characterMaximumLength = Number(typeDetails);
    } else if (typeDetails && field.type === 'numeric') {
      const match = /^(\d+)(?:\s*,\s*(-?\d+))?$/.exec(typeDetails);
      if (!match) throw new MigrationPlanError('invalid', `For Numeric field "${name}", enter precision and optional scale, such as 12, 2.`);
      numericPrecision = Number(match[1]);
      numericScale = match[2] === undefined ? 0 : Number(match[2]);
    } else if (typeDetails) {
      throw new MigrationPlanError('invalid', `${descriptor.label} fields do not accept size or precision parameters.`);
    }
    const type = formatFieldType({ type: field.type, characterMaximumLength, numericPrecision, numericScale });
    const identity = field.identityGeneration
      ? ` GENERATED ${field.identityGeneration === 'always' ? 'ALWAYS' : 'BY DEFAULT'} AS IDENTITY`
      : '';
    const defaultSql = field.defaultExpression?.trim()
      ? ` DEFAULT ${validateDefaultExpression(field.defaultExpression)}`
      : '';
    const nullability = !field.nullable && !field.identityGeneration ? ' NOT NULL' : '';
    return `  ${quoteIdentifier(name)} ${type}${identity}${defaultSql}${nullability}`;
  });
  const clause = ifNotExists ? ' IF NOT EXISTS' : '';
  return `CREATE TABLE${clause} ${quoteIdentifier(schema)}.${quoteIdentifier(table)} (\n${definitions.join(',\n')}\n);`;
}

async function validateForeignKeyTargets(
  client: Client,
  source: TableSnapshot,
  operations: SchemaOperation[],
): Promise<void> {
  const foreignKeys = operations.filter((operation) =>
    operation.kind === 'addConstraint' && operation.constraintKind === 'foreignKey');
  for (const operation of foreignKeys) {
    validatePostgresIdentifier(operation.referencedSchema, 'schema');
    validatePostgresIdentifier(operation.referencedTable, 'table');
    if (operation.fieldNames.length !== operation.referencedFieldNames.length) {
      throw new MigrationPlanError('invalid', 'A foreign key must pair each local field with exactly one referenced field.');
    }
    for (const field of operation.referencedFieldNames) validatePostgresIdentifier(field, 'field');

    const isSelfReference = operation.referencedSchema === source.schema && operation.referencedTable === source.name;
    const target = isSelfReference
      ? {
        kind: source.kind,
        fieldNames: source.fields.map(({ name }) => name),
        uniqueFieldSets: source.constraints
          .filter(({ kind }) => kind === 'primaryKey' || kind === 'unique')
          .map(({ fieldNames }) => fieldNames),
      }
      : await inspectForeignKeyTarget(client, operation.referencedSchema, operation.referencedTable);
    if (!target) {
      throw new MigrationPlanError('invalid', `The referenced table "${operation.referencedSchema}.${operation.referencedTable}" does not exist or is not visible.`);
    }
    if (target.kind !== 'table' && target.kind !== 'partitionedTable') {
      throw new MigrationPlanError('invalid', 'A foreign key can reference only a table or partitioned table.');
    }
    const missingField = operation.referencedFieldNames.find((name) => !target.fieldNames.includes(name));
    if (missingField) {
      throw new MigrationPlanError('invalid', `The referenced field "${missingField}" does not exist on "${operation.referencedSchema}.${operation.referencedTable}".`);
    }
    const referencedTypeResult = await client.query<{ name: string; typeName: string }>(`
      SELECT attribute.attname AS name, pg_catalog.format_type(attribute.atttypid, attribute.atttypmod) AS "typeName"
      FROM pg_catalog.pg_class relation
      JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
      JOIN pg_catalog.pg_attribute attribute ON attribute.attrelid = relation.oid
      WHERE namespace.nspname = $1 AND relation.relname = $2
        AND attribute.attnum > 0 AND NOT attribute.attisdropped AND attribute.attname = ANY($3::text[])
    `, [operation.referencedSchema, operation.referencedTable, operation.referencedFieldNames]);
    const referencedTypes = new Map(referencedTypeResult.rows.map((field) => [field.name, field.typeName]));
    for (let index = 0; index < operation.fieldNames.length; index += 1) {
      const localField = operation.fieldNames[index];
      const referencedField = operation.referencedFieldNames[index];
      const localType = source.fields.find(({ name }) => name === localField)?.typeName ?? '';
      const referencedType = referencedTypes.get(referencedField) ?? '';
      if (!typesCanReference(localType, referencedType)) {
        throw new MigrationPlanError('invalid', `The local field "${localField}" (${localType}) cannot reference "${operation.referencedSchema}.${operation.referencedTable}.${referencedField}" (${referencedType}). Choose fields with compatible PostgreSQL types.`);
      }
    }
    const requested = [...operation.referencedFieldNames].sort().join('\u0000');
    const hasUniqueTarget = target.uniqueFieldSets.some((fieldNames) => [...fieldNames].sort().join('\u0000') === requested);
    const plannedUniqueTarget = isSelfReference && operations.some((candidate) =>
      candidate.kind === 'addConstraint'
      && (candidate.constraintKind === 'primaryKey' || candidate.constraintKind === 'unique')
      && [...candidate.fieldNames].sort().join('\u0000') === requested);
    if (!hasUniqueTarget && !plannedUniqueTarget) {
      throw new MigrationPlanError('invalid', 'Referenced fields must match a primary key or unique constraint on the target table.');
    }
  }
}

async function inspectForeignKeyTarget(
  client: Client,
  schema: string,
  table: string,
): Promise<{ kind: string; fieldNames: string[]; uniqueFieldSets: string[][] } | undefined> {
  const targetResult = await client.query<{ kind: string }>(`
    SELECT CASE relation.relkind WHEN 'p' THEN 'partitionedTable' ELSE 'table' END AS kind
    FROM pg_catalog.pg_class relation
    JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = $1 AND relation.relname = $2 AND relation.relkind IN ('r', 'p')
  `, [schema, table]);
  if (!targetResult.rows[0]) return undefined;
  const fieldResult = await client.query<{ name: string }>(`
    SELECT attribute.attname AS name
    FROM pg_catalog.pg_class relation
    JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
    JOIN pg_catalog.pg_attribute attribute ON attribute.attrelid = relation.oid
    WHERE namespace.nspname = $1 AND relation.relname = $2
      AND attribute.attnum > 0 AND NOT attribute.attisdropped
    ORDER BY attribute.attnum
  `, [schema, table]);
  const uniqueResult = await client.query<{ fieldNames: string[] }>(`
    SELECT ARRAY(SELECT attribute.attname::text
      FROM unnest(idx.indkey) WITH ORDINALITY AS key_column(attnum, ordinal)
      JOIN pg_catalog.pg_attribute attribute ON attribute.attrelid = idx.indrelid AND attribute.attnum = key_column.attnum
      WHERE key_column.ordinal <= idx.indnkeyatts
      ORDER BY key_column.ordinal)::text[] AS "fieldNames"
    FROM pg_catalog.pg_index idx
    JOIN pg_catalog.pg_class relation ON relation.oid = idx.indrelid
    JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
    WHERE namespace.nspname = $1 AND relation.relname = $2
      AND idx.indisunique AND idx.indisvalid AND idx.indpred IS NULL AND idx.indexprs IS NULL
      AND NOT EXISTS (
        SELECT 1 FROM pg_catalog.pg_constraint constraint_row
        WHERE constraint_row.conindid = idx.indexrelid AND constraint_row.condeferrable
      )
  `, [schema, table]);
  return {
    kind: targetResult.rows[0].kind,
    fieldNames: fieldResult.rows.map(({ name }) => name),
    uniqueFieldSets: uniqueResult.rows.map(({ fieldNames }) => fieldNames),
  };
}

function typesCanReference(localType: string, targetType: string): boolean {
  const normalize = (type: string) => type.toLowerCase().replace(/\([^)]*\)/g, '').trim();
  const canonical = (type: string) => ({
    int2: 'smallint', int4: 'integer', int8: 'bigint', varchar: 'character varying',
    bpchar: 'character', float4: 'real', float8: 'double precision',
  } as Record<string, string>)[type] ?? type;
  const local = canonical(normalize(localType));
  const target = canonical(normalize(targetType));
  if (local === target) return true;
  const integer = new Set(['smallint', 'integer', 'bigint']);
  const text = new Set(['text', 'character varying', 'character']);
  return (integer.has(local) && integer.has(target)) || (text.has(local) && text.has(target));
}

function fieldTypeFor(dataType: string): string | null {
  if (dataType === 'character varying') return 'varchar';
  if (dataType === 'timestamp with time zone') return 'timestamptz';
  return POSTGRES_EDITABLE_FIELD_TYPES.find((type) => type.value === dataType)?.value ?? null;
}

function identityGenerationSupported(type: string): boolean {
  return POSTGRES_EDITABLE_FIELD_TYPES.find((descriptor) => descriptor.value === type)
    ?.identityGenerationSupported ?? false;
}

function normalizeFieldDraft(
  snapshot: TableSnapshot,
  draft: SchemaFieldDraftRequest['draft'],
): SchemaOperation | null {
  const name = draft.name.trim();
  if (!name) throw new MigrationPlanError('invalid', 'Enter a field name.');
  validateFieldName(name);
  const selectedType = POSTGRES_EDITABLE_FIELD_TYPES.find(({ value }) => value === draft.type);
  if (!selectedType) {
    throw new MigrationPlanError('invalid', 'Choose a field type supported by the connected database.');
  }
  const type = selectedType.value as NullableFieldType;
  const typeDetails = draft.typeDetails.trim();
  let characterMaximumLength: number | null = null;
  let numericPrecision: number | null = null;
  let numericScale: number | null = null;
  if (typeDetails && type === 'varchar') {
    if (!/^\d+$/.test(typeDetails)) {
      throw new MigrationPlanError('invalid', 'For Varchar, enter a positive maximum length, such as 255.');
    }
    characterMaximumLength = Number(typeDetails);
    if (characterMaximumLength < 1 || characterMaximumLength > 10_485_760) {
      throw new MigrationPlanError('invalid', 'Varchar length must be between 1 and 10,485,760 characters.');
    }
  } else if (typeDetails && type === 'numeric') {
    const match = /^(\d+)(?:\s*,\s*(-?\d+))?$/.exec(typeDetails);
    if (!match) throw new MigrationPlanError('invalid', 'For Numeric, enter precision and optional scale, such as 12, 2.');
    numericPrecision = Number(match[1]);
    numericScale = match[2] === undefined ? 0 : Number(match[2]);
    if (numericPrecision < 1 || numericPrecision > 1000 || numericScale < -1000 || numericScale > 1000) {
      throw new MigrationPlanError('invalid', 'Numeric precision must be 1–1000 and scale must be -1000–1000.');
    }
  } else if (typeDetails) {
    const typeLabel = selectedType.label;
    const explanation = type === 'text'
      ? 'PostgreSQL text fields are unbounded and do not have a maximum size. Leave Size / precision blank, or choose Varchar and enter a length, such as 255.'
      : `PostgreSQL ${typeLabel} fields do not accept size or precision parameters. Leave Size / precision blank.`;
    throw new MigrationPlanError('invalid', explanation);
  }

  const defaultValue = draft.defaultValue.trim();
  const defaultExpression = defaultValue && defaultValue !== '—'
    ? validateDefaultExpression(defaultValue)
    : null;
  let identityGeneration = draft.identityGeneration === undefined
    ? null
    : draft.identityGeneration === 'none' ? null : draft.identityGeneration;
  const identityType = selectedType.identityGenerationSupported;
  if (draft.sourceName === null) {
    if (identityGeneration && !identityType) {
      throw new MigrationPlanError('invalid', 'PostgreSQL identity columns require a Small integer, Integer, or Big integer field type.');
    }
    if (identityGeneration && defaultExpression) {
      throw new MigrationPlanError('invalid', 'An identity column cannot also have a default. Clear the default before staging the field.');
    }
    return { kind: 'addNullableField', name, type, typeDetails, characterMaximumLength, numericPrecision, numericScale, defaultExpression, identityGeneration };
  }

  const field = snapshot.fields.find(({ name: fieldName }) => fieldName === draft.sourceName);
  if (!field) throw new MigrationPlanError('invalid', `The field "${draft.sourceName}" no longer exists.`);
  if (draft.identityGeneration === undefined) identityGeneration = field.identityGeneration;
  if (field.generated) {
    throw new MigrationPlanError('invalid', `Generated field "${draft.sourceName}" cannot be edited by this migration.`);
  }
  if (identityGeneration && !identityType) {
    throw new MigrationPlanError('invalid', 'PostgreSQL identity columns require a Small integer, Integer, or Big integer field type.');
  }
  if (identityGeneration && defaultExpression) {
    throw new MigrationPlanError('invalid', 'An identity column cannot also have a default. Clear the default before staging this change.');
  }
  const nullable = identityGeneration ? false : draft.nullable ?? field.nullable;
  const currentDefault = field.defaultExpression?.trim() ?? null;
  if (name === field.name && fieldTypeFor(field.dataType) === type
    && field.characterMaximumLength === characterMaximumLength
    && field.numericPrecision === numericPrecision && field.numericScale === numericScale
    && currentDefault === defaultExpression && field.nullable === nullable
    && field.identityGeneration === identityGeneration) return null;
  return {
    kind: 'alterField', name: draft.sourceName, newName: name, type, typeDetails,
    characterMaximumLength, numericPrecision, numericScale, defaultExpression, nullable, identityGeneration,
  };
}

/** @internal Pure SQL generation helper; exported for the migration-plan unit tests. */
export function createMigrationPreview(snapshot: TableSnapshot, request: MigrationPreviewRequest): string[] {
  if (snapshot.kind !== 'table' && snapshot.kind !== 'partitionedTable') {
    throw new MigrationPlanError('invalid', 'Only PostgreSQL tables can be renamed, dropped, or altered.');
  }
  const lifecycle = request.operations[0];
  if (lifecycle?.kind === 'renameTable') {
    validatePostgresIdentifier(lifecycle.newName, 'table');
    if (lifecycle.newName === snapshot.name) {
      throw new MigrationPlanError('invalid', 'Choose a different name for the table.');
    }
    return [`ALTER TABLE ${quoteIdentifier(snapshot.schema)}.${quoteIdentifier(snapshot.name)} RENAME TO ${quoteIdentifier(lifecycle.newName)};`];
  }
  if (lifecycle?.kind === 'dropTable') {
    return [`DROP TABLE ${quoteIdentifier(snapshot.schema)}.${quoteIdentifier(snapshot.name)};`];
  }
  const table = `${quoteIdentifier(snapshot.schema)}.${quoteIdentifier(snapshot.name)}`;
  const currentNames = new Set(snapshot.fields.map(({ name }) => name));
  const fieldOperations = request.operations.filter((operation) =>
    operation.kind === 'addNullableField' || operation.kind === 'alterField');
  const renamedFieldNames = new Map(fieldOperations.flatMap((operation) =>
    operation.kind === 'alterField' ? [[operation.name, operation.newName] as const] : []));
  const availableFieldNames = new Set([
    ...currentNames,
    ...fieldOperations.flatMap((operation) => operation.kind === 'addNullableField' ? [operation.name] : [operation.newName]),
  ]);
  const finalNames = new Map<string, string>();
  const fieldSources = new Set<string>();
  const constraintSources = new Map<string, 'add' | 'drop'>();
  const currentConstraintNames = new Set(snapshot.constraints.map(({ name }) => name));
  for (const operation of request.operations) {
    if (operation.kind === 'createTable') {
      throw new MigrationPlanError('invalid', 'Create-table operations require a new-table baseline.');
    }
    if (operation.kind === 'addNullableField') {
      validateFieldName(operation.name);
      if (operation.identityGeneration && !identityGenerationSupported(operation.type)) {
        throw new MigrationPlanError('invalid', 'PostgreSQL identity columns require the smallint, integer, or bigint type.');
      }
      if (operation.identityGeneration && operation.defaultExpression) {
        throw new MigrationPlanError('invalid', 'An identity column cannot also have a default expression.');
      }
      if (fieldSources.has(operation.name)) {
        throw new MigrationPlanError('invalid', `A field operation for "${operation.name}" appears more than once.`);
      }
      fieldSources.add(operation.name);
      if (currentNames.has(operation.name) || [...finalNames.values()].includes(operation.name)) {
        throw new MigrationPlanError('invalid', `A field named "${operation.name}" already exists or is already in this plan.`);
      }
      finalNames.set(operation.name, operation.name);
    } else if (operation.kind === 'alterField') {
      validateFieldName(operation.newName);
      if (fieldSources.has(operation.name)) {
        throw new MigrationPlanError('invalid', `A field operation for "${operation.name}" appears more than once.`);
      }
      fieldSources.add(operation.name);
      if (!currentNames.has(operation.name)) {
        throw new MigrationPlanError('invalid', `The field "${operation.name}" no longer exists.`);
      }
      const targetName = operation.newName;
      const collision = snapshot.fields.some(({ name }) => name === targetName && name !== operation.name)
        || [...finalNames.values()].includes(targetName);
      if (collision) throw new MigrationPlanError('invalid', `A field named "${targetName}" already exists or is already in this plan.`);
      finalNames.set(operation.name, targetName);
    } else if (operation.kind === 'addConstraint') {
      validatePostgresIdentifier(operation.name, 'constraint');
      const previousConstraintOperation = constraintSources.get(operation.name);
      if (previousConstraintOperation === 'add'
        || (previousConstraintOperation === 'drop' && !currentConstraintNames.has(operation.name))) {
        throw new MigrationPlanError('invalid', `A constraint operation for "${operation.name}" appears more than once.`);
      }
      constraintSources.set(operation.name, 'add');
      const scheduledDrop = request.operations.some((candidate) =>
        candidate.kind === 'dropConstraint' && candidate.name === operation.name);
      if (currentConstraintNames.has(operation.name) && !scheduledDrop) {
        throw new MigrationPlanError('invalid', `A constraint named "${operation.name}" already exists on this table.`);
      }
      const replacingPrimaryKey = request.operations.some((candidate) => candidate.kind === 'dropConstraint'
        && snapshot.constraints.some(({ name, kind }) => name === candidate.name && kind === 'primaryKey'));
      if (operation.constraintKind === 'primaryKey'
        && snapshot.constraints.some(({ kind }) => kind === 'primaryKey') && !replacingPrimaryKey) {
        throw new MigrationPlanError('invalid', 'This table already has a primary key. Drop it before adding another.');
      }
      if (operation.constraintKind === 'primaryKey'
        && request.operations.some((candidate) => candidate.kind === 'addConstraint' && candidate.constraintKind === 'primaryKey'
          && candidate !== operation)) {
        throw new MigrationPlanError('invalid', 'A table can have only one primary key.');
      }
      if (operation.constraintKind === 'check') {
        normalizeCheckExpression(operation.expression, availableFieldNames, renamedFieldNames);
      } else {
        const seenFields = new Set<string>();
        for (const name of operation.fieldNames) {
          validatePostgresIdentifier(name, 'field');
          if (!availableFieldNames.has(name)) throw new MigrationPlanError('invalid', `The field "${name}" does not exist on this table or in this plan.`);
          const resolvedName = renamedFieldNames.get(name) ?? name;
          if (seenFields.has(resolvedName)) throw new MigrationPlanError('invalid', `The field "${name}" appears more than once in this constraint.`);
          seenFields.add(resolvedName);
        }
      }
    } else if (operation.kind === 'dropConstraint') {
      validatePostgresIdentifier(operation.name, 'constraint');
      const previousConstraintOperation = constraintSources.get(operation.name);
      if (previousConstraintOperation === 'drop'
        || (previousConstraintOperation === 'add' && !currentConstraintNames.has(operation.name))) {
        throw new MigrationPlanError('invalid', `A constraint operation for "${operation.name}" appears more than once.`);
      }
      constraintSources.set(operation.name, 'drop');
      const constraint = snapshot.constraints.find(({ name }) => name === operation.name);
      if (!constraint) throw new MigrationPlanError('invalid', `The constraint "${operation.name}" no longer exists.`);
      if (constraint.kind !== 'primaryKey' && constraint.kind !== 'unique'
        && constraint.kind !== 'check' && constraint.kind !== 'foreignKey') {
        throw new MigrationPlanError('invalid', `Removing ${constraint.kind} constraints is not supported yet.`);
      }
    }
  }

  const orderedOperations = [
    ...request.operations.filter((operation) => operation.kind === 'dropConstraint'),
    ...fieldOperations,
    ...request.operations.filter((operation) => operation.kind === 'addConstraint'),
  ];
  return orderedOperations.flatMap((operation) => {
    if (operation.kind === 'addNullableField') {
      const typeSql = formatFieldType(operation);
      const identitySql = operation.identityGeneration
        ? ` GENERATED ${operation.identityGeneration === 'always' ? 'ALWAYS' : 'BY DEFAULT'} AS IDENTITY`
        : '';
      const defaultSql = operation.defaultExpression ? ` DEFAULT ${validateDefaultExpression(operation.defaultExpression)}` : '';
      return [`ALTER TABLE ${table} ADD COLUMN ${quoteIdentifier(operation.name)} ${typeSql}${identitySql}${defaultSql};`];
    }
    if (operation.kind === 'alterField') return statementsForAlterField(table, snapshot, operation);
    if (operation.kind === 'dropConstraint') {
      return [`ALTER TABLE ${table} DROP CONSTRAINT ${quoteIdentifier(operation.name)};`];
    }
    if (operation.constraintKind === 'check') {
      const expression = normalizeCheckExpression(operation.expression, availableFieldNames, renamedFieldNames);
      return [`ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(operation.name)} CHECK (${expression});`];
    }
    const fields = operation.fieldNames.map((name) => quoteIdentifier(renamedFieldNames.get(name) ?? name)).join(', ');
    if (operation.constraintKind === 'foreignKey') {
      const referencedFields = operation.referencedFieldNames.map(quoteIdentifier).join(', ');
      const target = `${quoteIdentifier(operation.referencedSchema)}.${quoteIdentifier(operation.referencedTable)}`;
      return [`ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(operation.name)} FOREIGN KEY (${fields}) REFERENCES ${target} (${referencedFields});`];
    }
    const kindSql = operation.constraintKind === 'primaryKey' ? 'PRIMARY KEY' : 'UNIQUE';
    return [`ALTER TABLE ${table} ADD CONSTRAINT ${quoteIdentifier(operation.name)} ${kindSql} (${fields});`];
  });
}

function statementsForAlterField(
  table: string,
  snapshot: TableSnapshot,
  operation: Extract<SchemaOperation, { kind: 'alterField' }>,
): string[] {
  const field = snapshot.fields.find(({ name }) => name === operation.name);
  if (!field) throw new MigrationPlanError('invalid', `The field "${operation.name}" no longer exists.`);
  if (field.generated) {
    throw new MigrationPlanError('invalid', `Generated field "${operation.name}" cannot be edited by this migration.`);
  }
  const identityGeneration = operation.identityGeneration === undefined
    ? field.identityGeneration
    : operation.identityGeneration;
  if (identityGeneration && !identityGenerationSupported(operation.type)) {
    throw new MigrationPlanError('invalid', 'PostgreSQL identity columns require the smallint, integer, or bigint type.');
  }
  if (identityGeneration && operation.defaultExpression) {
    throw new MigrationPlanError('invalid', 'An identity column cannot also have a default expression.');
  }
  if (field.identityGeneration && identityGeneration && !sameFieldType(field, operation)) {
    throw new MigrationPlanError('invalid', 'Change an identity field’s type only after removing its identity generation.');
  }

  const statements: string[] = [];
  const oldName = quoteIdentifier(operation.name);
  const finalName = quoteIdentifier(operation.newName);
  if (operation.newName !== operation.name) {
    statements.push(`ALTER TABLE ${table} RENAME COLUMN ${oldName} TO ${finalName};`);
  }

  const targetType = formatFieldType(operation);
  const typeChanged = !sameFieldType(field, operation);
  const currentDefault = field.defaultExpression?.trim() ?? null;
  const nextDefault = operation.defaultExpression?.trim() ?? null;
  if (field.identityGeneration && identityGeneration === null) {
    statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} DROP IDENTITY;`);
  }
  if (typeChanged && currentDefault !== null) {
    statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} DROP DEFAULT;`);
  }
  if (typeChanged) {
    statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} TYPE ${targetType};`);
  }

  const defaultChanged = currentDefault !== nextDefault;
  if (typeChanged) {
    if (nextDefault !== null) {
      statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} SET DEFAULT ${validateDefaultExpression(nextDefault)};`);
    }
  } else if (defaultChanged) {
    statements.push(nextDefault === null
      ? `ALTER TABLE ${table} ALTER COLUMN ${finalName} DROP DEFAULT;`
      : `ALTER TABLE ${table} ALTER COLUMN ${finalName} SET DEFAULT ${validateDefaultExpression(nextDefault)};`);
  }
  const nullable = identityGeneration ? false : operation.nullable ?? field.nullable;
  if (nullable !== field.nullable) {
    statements.push(nullable
      ? `ALTER TABLE ${table} ALTER COLUMN ${finalName} DROP NOT NULL;`
      : `ALTER TABLE ${table} ALTER COLUMN ${finalName} SET NOT NULL;`);
  }
  if (!field.identityGeneration && identityGeneration) {
    statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} ADD GENERATED ${identityGeneration === 'always' ? 'ALWAYS' : 'BY DEFAULT'} AS IDENTITY;`);
  } else if (field.identityGeneration && identityGeneration && field.identityGeneration !== identityGeneration) {
    statements.push(`ALTER TABLE ${table} ALTER COLUMN ${finalName} SET GENERATED ${identityGeneration === 'always' ? 'ALWAYS' : 'BY DEFAULT'};`);
  }
  return statements;
}

function sameFieldType(
  field: TableFieldDescriptor,
  operation: Extract<SchemaOperation, { kind: 'alterField' }>,
): boolean {
  const existingType = normalizeFieldType(field.dataType);
  if (existingType !== operation.type) return false;
  if (operation.type === 'varchar') return field.characterMaximumLength === operation.characterMaximumLength;
  if (operation.type === 'numeric') {
    return field.numericPrecision === operation.numericPrecision && field.numericScale === operation.numericScale;
  }
  return true;
}

function normalizeFieldType(dataType: string): string {
  if (dataType === 'character varying') return 'varchar';
  if (dataType === 'timestamp with time zone') return 'timestamptz';
  if (dataType === 'bigint') return 'bigint';
  if (dataType === 'integer') return 'integer';
  return dataType;
}

function formatFieldType(operation: Pick<Extract<SchemaOperation, { kind: 'addNullableField' | 'alterField' }>, 'type'> & {
  characterMaximumLength?: number | null;
  numericPrecision?: number | null;
  numericScale?: number | null;
}): string {
  if (operation.type === 'varchar') {
    if (operation.characterMaximumLength != null
      && (!Number.isInteger(operation.characterMaximumLength) || operation.characterMaximumLength < 1 || operation.characterMaximumLength > 10_485_760)) {
      throw new MigrationPlanError('invalid', 'Varchar length must be a whole number between 1 and 10,485,760 characters.');
    }
    return operation.characterMaximumLength ? `character varying(${operation.characterMaximumLength})` : 'character varying';
  }
  if (operation.type === 'numeric') {
    if ((operation.numericScale !== null && operation.numericScale !== undefined)
      && (operation.numericPrecision === null || operation.numericPrecision === undefined)) {
      throw new MigrationPlanError('invalid', 'Numeric scale requires a precision.');
    }
    if (operation.numericPrecision != null
      && (!Number.isInteger(operation.numericPrecision) || operation.numericPrecision < 1 || operation.numericPrecision > 1000)) {
      throw new MigrationPlanError('invalid', 'Numeric precision must be a whole number from 1 to 1000.');
    }
    if (operation.numericScale != null
      && (!Number.isInteger(operation.numericScale) || operation.numericScale < -1000 || operation.numericScale > 1000)) {
      throw new MigrationPlanError('invalid', 'Numeric scale must be a whole number from -1000 to 1000.');
    }
    if (operation.numericPrecision === null || operation.numericPrecision === undefined) return 'numeric';
    const scale = operation.numericScale ?? 0;
    return `numeric(${operation.numericPrecision}, ${scale})`;
  }
  if (operation.characterMaximumLength != null || operation.numericPrecision != null || operation.numericScale != null) {
    const typeLabel = operation.type === 'timestamptz' ? 'timestamp with time zone' : operation.type;
    const explanation = operation.type === 'text'
      ? 'PostgreSQL text fields are unbounded and do not accept a maximum size. Leave Size / precision blank, or use Varchar and enter a length such as 255.'
      : `PostgreSQL ${typeLabel} fields do not accept size or precision parameters. Leave them blank; Varchar accepts a length, and Numeric accepts precision and scale.`;
    throw new MigrationPlanError('invalid', explanation);
  }
  const typeSql = {
    text: 'text', smallint: 'smallint', integer: 'integer', bigint: 'bigint', boolean: 'boolean', uuid: 'uuid',
    date: 'date', timestamptz: 'timestamp with time zone', jsonb: 'jsonb',
  } as const;
  const sqlType = typeSql[operation.type as keyof typeof typeSql];
  if (!sqlType) throw new MigrationPlanError('invalid', `The connected database does not support the field type "${operation.type}".`);
  return sqlType;
}

/** @internal Pure warning generation helper; exported for the migration-plan unit tests. */
export function collectMigrationWarnings(snapshot: TableSnapshot, operations: SchemaOperation[]): string[] {
  const warnings: string[] = [];
  for (const operation of operations) {
    if (operation.kind === 'dropTable') {
      warnings.push(`Dropping ${snapshot.schema}.${snapshot.name} permanently removes the table and its data. PostgreSQL will reject the drop if other objects depend on it.`);
    }
    if (operation.kind === 'addNullableField' && operation.defaultExpression) {
      warnings.push(`Adding "${operation.name}" with a default may populate existing rows. Review the expression and resulting SQL.`);
    }
    if (operation.kind === 'addNullableField' && operation.identityGeneration) {
      warnings.push(`Adding "${operation.name}" as an identity column generates values for existing rows and rewrites the table. Review the lock and migration duration before applying.`);
    }
    if (operation.kind === 'alterField') {
      const field = snapshot.fields.find(({ name }) => name === operation.name);
      if (field && !sameFieldType(field, operation)) {
        warnings.push(`Changing the type of "${operation.name}" may fail or transform existing values. Review the conversion before applying.`);
      }
      if (field?.nullable && operation.nullable === false) {
        warnings.push(`Making "${operation.name}" NOT NULL may fail if existing rows contain NULL values. Review the data before applying.`);
      }
      if (field && !field.identityGeneration && operation.identityGeneration) {
        warnings.push(`Adding identity generation to "${operation.name}" makes it NOT NULL and does not replace existing values. Check for NULLs and ensure the sequence will not collide with existing values.`);
      }
    }
    if (operation.kind === 'addConstraint' && operation.constraintKind === 'primaryKey') {
      const nullableFields = operation.fieldNames.filter((name) => snapshot.fields.find((field) => field.name === name)?.nullable);
      if (nullableFields.length) {
        warnings.push(`Adding a primary key makes ${nullableFields.map((name) => `"${name}"`).join(', ')} NOT NULL and may fail if existing rows contain NULL values.`);
      }
    }
    if (operation.kind === 'addConstraint' && operation.constraintKind === 'check') {
      warnings.push(`Adding the CHECK constraint "${operation.name}" may fail if existing rows do not satisfy its expression.`);
    }
    if (operation.kind === 'addConstraint' && operation.constraintKind === 'foreignKey') {
      warnings.push(`Adding the foreign key "${operation.name}" validates existing rows and may fail if any local value has no matching referenced row.`);
    }
    if (operation.kind === 'dropConstraint') {
      const constraint = snapshot.constraints.find(({ name }) => name === operation.name);
      if (constraint) warnings.push(`Dropping the ${constraint.kind} constraint "${operation.name}" reduces database integrity protection. Review dependent data and objects.`);
    }
  }
  return warnings;
}

function validateTableLifecycleOperations(operations: SchemaOperation[]): void {
  const lifecycle = operations.filter((operation) => operation.kind === 'renameTable' || operation.kind === 'dropTable');
  if (lifecycle.length && (lifecycle.length !== 1 || operations.length !== 1)) {
    throw new MigrationPlanError('invalid', 'Rename or drop a table in its own runbook batch.');
  }
}

async function validateTableLifecycleTarget(
  client: Client,
  snapshot: TableSnapshot,
  operations: SchemaOperation[],
): Promise<void> {
  const operation = operations[0];
  if (operation?.kind !== 'renameTable') return;
  validatePostgresIdentifier(operation.newName, 'table');
  if (operation.newName === snapshot.name) throw new MigrationPlanError('invalid', 'Choose a different name for the table.');
  const existing = await client.query<{ exists: boolean }>(`
    SELECT EXISTS (
      SELECT 1 FROM pg_catalog.pg_class relation
      JOIN pg_catalog.pg_namespace namespace ON namespace.oid = relation.relnamespace
      WHERE namespace.nspname = $1 AND relation.relname = $2
    ) AS exists
  `, [snapshot.schema, operation.newName]);
  if (existing.rows[0]?.exists) {
    throw new MigrationPlanError('invalid', `A table or relation named "${operation.newName}" already exists in schema "${snapshot.schema}".`);
  }
}

function validateFieldName(name: string): void {
  validatePostgresIdentifier(name, 'field');
}

function validatePostgresIdentifier(name: string, kind: 'schema' | 'table' | 'field' | 'constraint'): void {
  if (!name.trim() || name.includes('\0') || Buffer.byteLength(name, 'utf8') > 63) {
    throw new MigrationPlanError('invalid', `Enter a non-empty PostgreSQL ${kind} name that fits within 63 bytes.`);
  }
}

function validateDefaultExpression(expression: string): string {
  const trimmed = expression.trim();
  if (!trimmed || trimmed.length > 2048 || /[;\u0000]|--|\/\*/.test(trimmed)) {
    throw new MigrationPlanError('invalid', 'Enter a single SQL default expression without statement separators or comments.');
  }
  return trimmed;
}

function quoteIdentifier(identifier: string): string {
  return `"${identifier.replaceAll('"', '""')}"`;
}

type CheckToken = { kind: 'identifier' | 'number' | 'string' | 'operator' | 'punctuation'; value: string; quoted?: boolean };

function normalizeCheckExpression(
  source: string,
  availableFieldNames: Set<string>,
  renamedFieldNames: Map<string, string>,
): string {
  const tokens = tokenizeCheckExpression(source);
  let position = 0;
  const peek = (value?: string): boolean => {
    const token = tokens[position];
    if (!token) return false;
    if (value === undefined) return true;
    const keyword = ['AND', 'BETWEEN', 'FALSE', 'ILIKE', 'IN', 'IS', 'LIKE', 'NOT', 'NULL', 'OR', 'TRUE'];
    if (token.quoted && keyword.includes(value.toUpperCase())) return false;
    return token.value.toUpperCase() === value.toUpperCase();
  };
  const take = (value?: string): CheckToken => {
    const token = tokens[position];
    if (!token || (value !== undefined && token.value.toUpperCase() !== value)) {
      throw new MigrationPlanError('invalid', `Expected ${value ?? 'an expression value'} in the CHECK expression.`);
    }
    position += 1;
    return token;
  };
  const fieldSql = (token: CheckToken): string => {
    const name = token.quoted ? token.value : token.value.toLowerCase();
    if (!availableFieldNames.has(name)) {
      throw new MigrationPlanError('invalid', `The field "${name}" in the CHECK expression does not exist on this table or in this plan.`);
    }
    return quoteIdentifier(renamedFieldNames.get(name) ?? name);
  };
  const parsePrimary = (): string => {
    if (peek('(')) {
      take('(');
      const expression = parseOr();
      take(')');
      return `(${expression})`;
    }
    const token = take();
    if (token.kind === 'identifier') {
      if (!token.quoted && ['TRUE', 'FALSE', 'NULL'].includes(token.value.toUpperCase())) {
        return token.value.toUpperCase();
      }
      return fieldSql(token);
    }
    if (token.kind === 'number' || token.kind === 'string') return token.value;
    throw new MigrationPlanError('invalid', 'Use table fields, numbers, quoted strings, TRUE, FALSE, or NULL in the CHECK expression.');
  };
  const parseUnary = (): string => {
    if (peek('+') || peek('-')) return `${take().value}${parseUnary()}`;
    return parsePrimary();
  };
  const parseMultiply = (): string => {
    let expression = parseUnary();
    while (peek('*') || peek('/') || peek('%')) expression = `(${expression} ${take().value} ${parseUnary()})`;
    return expression;
  };
  const parseAdd = (): string => {
    let expression = parseMultiply();
    while (peek('+') || peek('-')) expression = `(${expression} ${take().value} ${parseMultiply()})`;
    return expression;
  };
  const parseCompare = (): string => {
    const left = parseAdd();
    if (peek('IS')) {
      take('IS');
      const not = peek('NOT') ? (take('NOT'), ' NOT') : '';
      take('NULL');
      return `(${left} IS${not} NULL)`;
    }
    let not = false;
    if (peek('NOT')) {
      take('NOT');
      not = true;
    }
    if (peek('IN')) {
      take('IN');
      take('(');
      const values = [parseAdd()];
      while (peek(',')) { take(','); values.push(parseAdd()); }
      take(')');
      return `(${left}${not ? ' NOT' : ''} IN (${values.join(', ')}))`;
    }
    if (peek('BETWEEN')) {
      take('BETWEEN');
      const lower = parseAdd();
      take('AND');
      const upper = parseAdd();
      return `(${left}${not ? ' NOT' : ''} BETWEEN ${lower} AND ${upper})`;
    }
    if (peek('LIKE') || peek('ILIKE')) return `(${left}${not ? ' NOT' : ''} ${take().value.toUpperCase()} ${parseAdd()})`;
    if (not) throw new MigrationPlanError('invalid', 'NOT in a CHECK expression must be followed by IN, BETWEEN, LIKE, or ILIKE.');
    if (tokens[position]?.kind === 'operator') return `(${left} ${take().value} ${parseAdd()})`;
    return left;
  };
  const parseNot = (): string => {
    if (peek('NOT')) {
      take('NOT');
      return `(NOT ${parseNot()})`;
    }
    return parseCompare();
  };
  const parseAnd = (): string => {
    let expression = parseNot();
    while (peek('AND')) { take('AND'); expression = `(${expression} AND ${parseNot()})`; }
    return expression;
  };
  const parseOr = (): string => {
    let expression = parseAnd();
    while (peek('OR')) { take('OR'); expression = `(${expression} OR ${parseAnd()})`; }
    return expression;
  };

  const expression = parseOr();
  if (position !== tokens.length) {
    throw new MigrationPlanError('invalid', 'The CHECK expression contains unsupported SQL. Use fields, literals, comparisons, IN, BETWEEN, LIKE, AND, OR, NOT, and parentheses.');
  }
  return expression;
}

function tokenizeCheckExpression(source: string): CheckToken[] {
  const tokens: CheckToken[] = [];
  let position = 0;
  while (position < source.length) {
    if (/\s/.test(source[position])) { position += 1; continue; }
    const start = position;
    const character = source[position];
    if (character === '"') {
      position += 1;
      let value = '';
      let closed = false;
      while (position < source.length) {
        if (source[position] === '"') {
          if (source[position + 1] === '"') { value += '"'; position += 2; }
          else { position += 1; closed = true; break; }
        } else value += source[position++];
      }
      if (!closed) throw new MigrationPlanError('invalid', 'Close the quoted field name in the CHECK expression.');
      tokens.push({ kind: 'identifier', value, quoted: true });
    } else if (character === "'") {
      position += 1;
      let closed = false;
      while (position < source.length) {
        if (source[position] === "'") {
          if (source[position + 1] === "'") position += 2;
          else { position += 1; closed = true; break; }
        } else position += 1;
      }
      if (!closed) throw new MigrationPlanError('invalid', 'Close the quoted string in the CHECK expression.');
      tokens.push({ kind: 'string', value: source.slice(start, position) });
    } else if (/[0-9]/.test(character)) {
      const match = /^(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?/.exec(source.slice(position));
      if (!match) throw new MigrationPlanError('invalid', 'Enter a valid number in the CHECK expression.');
      position += match[0].length;
      tokens.push({ kind: 'number', value: match[0] });
    } else if (/[A-Za-z_]/.test(character)) {
      const match = /^[A-Za-z_][A-Za-z0-9_$]*/.exec(source.slice(position));
      if (!match) throw new MigrationPlanError('invalid', 'Enter a valid field name in the CHECK expression.');
      position += match[0].length;
      tokens.push({ kind: 'identifier', value: match[0] });
    } else if (['<=', '>=', '<>', '!='].some((operator) => source.startsWith(operator, position))) {
      const value = ['<=', '>=', '<>', '!='].find((operator) => source.startsWith(operator, position))!;
      position += value.length;
      tokens.push({ kind: 'operator', value });
    } else if ('=<>'.includes(character)) {
      position += 1;
      tokens.push({ kind: 'operator', value: character });
    } else if ('(),+-*/%'.includes(character)) {
      position += 1;
      tokens.push({ kind: 'punctuation', value: character });
    } else {
      throw new MigrationPlanError('invalid', `The character "${character}" is not supported in a CHECK expression.`);
    }
  }
  if (!tokens.length) throw new MigrationPlanError('invalid', 'Enter a CHECK expression.');
  return tokens;
}

function sameStatements(expected: string[], reviewed: string[]): boolean {
  return expected.length === reviewed.length && expected.every((statement, index) => statement === reviewed[index]);
}

function constraintKind(
  kind: ConstraintRow['constraintType'],
): TableConstraintDescriptor['kind'] {
  switch (kind) {
    case 'p': return 'primaryKey';
    case 'u': return 'unique';
    case 'f': return 'foreignKey';
    case 'c': return 'check';
    case 'x': return 'exclusion';
  }
}

function safeDatabaseMessage(error: unknown): string {
  const details = typeof error === 'object' && error !== null
    ? error as { code?: unknown; message?: unknown }
    : undefined;
  const code = typeof details?.code === 'string' ? details.code : '';
  const databaseMessage = typeof details?.message === 'string' ? details.message : '';
  if (code === '28P01' || code === '28000') return 'PostgreSQL authentication failed. Check the username and password.';
  if (code === '3D000') return 'The PostgreSQL database was not found. Check the database name.';
  if (code === '42501') return 'The PostgreSQL user does not have permission to inspect this resource.';
  if (code === '42804') return 'The local and referenced foreign-key fields must use compatible PostgreSQL types.';
  if (code === '23503') return 'Existing rows violate the foreign key. Check that each local value has a matching referenced row.';
  if (code === '42703' && databaseMessage.includes('indnkeyatts')) {
    return 'This PostgreSQL version does not expose the index metadata needed to list foreign-key target fields. Use PostgreSQL 11 or later.';
  }
  if (['ECONNREFUSED', 'ENOTFOUND', 'ETIMEDOUT', 'EHOSTUNREACH', 'ENETUNREACH'].includes(code)) {
    return 'Could not reach PostgreSQL. Check the host, port, and server availability.';
  }
  if (code) return `The PostgreSQL request failed (SQLSTATE ${code}). Check the server version and database permissions.`;
  return 'The PostgreSQL request failed. Check the connection settings and database permissions.';
}

function migrationDatabaseMessage(error: unknown): string {
  const details = typeof error === 'object' && error !== null
    ? error as { code?: unknown; constraint?: unknown }
    : undefined;
  if (details?.code === '23514') {
    const constraint = typeof details.constraint === 'string'
      ? ` "${details.constraint}"`
      : '';
    return `The migration violates CHECK constraint${constraint}: one or more rows do not satisfy its expression. PostgreSQL rolled back the transaction, so none of the migration changes were applied. Update the expression or affected data, then apply again.`;
  }
  return safeDatabaseMessage(error);
}
